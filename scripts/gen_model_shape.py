#!/usr/bin/env python3
"""Writes crates/supervisor/src/model_shape.rs: the tensor names and byte lengths the graph implements.

Usage: python3 scripts/gen_model_shape.py FULL_MANIFEST SMALL_MANIFEST BUILD

FULL_MANIFEST and SMALL_MANIFEST are the `manifest.json` files that `neural-forge-cli extract-model`
wrote with `--network full` and `--network small` from one DLL whose networks OpenDLSS-NR's graph at
the pinned commit (third_party/opendlss-nr/UPSTREAM.md, with patches/0009) implements; BUILD is that
DLL's build, for the file comment. Only each tensor's `name` and `byteLength` are read: no tensor
bytes, no hashes.
"""

import json
import pathlib
import re
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/supervisor/src/model_shape.rs"


def pinned_commit() -> str:
    upstream = OUT.parents[3] / "third_party/opendlss-nr/UPSTREAM.md"
    found = re.search(r"Commit: `([0-9a-f]{40})`", upstream.read_text())
    if not found:
        sys.exit(f"no commit line in {upstream}")
    return found.group(1)


def rows(path: str) -> list:
    return [(t["name"], int(t["byteLength"])) for t in json.loads(pathlib.Path(path).read_text())["tensors"]]


def table(name: str, doc: str, entries: list) -> list:
    lines = [f"/// {doc}", f"pub const {name}: &[(&str, u64)] = &["]
    lines += [f'    ("{n}", {length}),' for n, length in entries]
    lines.append("];")
    return lines


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(__doc__.strip().splitlines()[2])
    full, small, build = rows(sys.argv[1]), rows(sys.argv[2]), sys.argv[3]
    lines = [
        "//! The tensors the graph implements: each name in the weights resource and its byte length, for",
        "//! the full network (`WEIGHTS_HT`) and the small one (`WEIGHTS_CC_SMALL_FP8`).",
        "//!",
        f"//! Generated by `scripts/gen_model_shape.py` from the manifests `extract-model` wrote from build {build}.",
        "//! The rows describe the networks in OpenDLSS-NR at the pinned commit (`third_party/opendlss-nr/UPSTREAM.md`)",
        f"//! `{pinned_commit()}` with patches/0009. Moving the pin to a new network changes these tables with it:",
        "//! regenerate them from manifests of a DLL that carries the new network.",
        "//!",
        "//! Names and lengths only: no tensor bytes and no hashes of them.",
        "",
    ]
    lines += table("EXPECTED", "The full network: `(name, byte length)`, in the manifest's order (stage, then block, layer and parameter).", full)
    lines.append("")
    lines += table("EXPECTED_SMALL", "The small network, in the same order.", small)
    OUT.write_text("\n".join(lines) + "\n")
    for label, entries in (("full", full), ("small", small)):
        print(f"{OUT}: {label} {len(entries)} tensors, {sum(length for _, length in entries)} bytes")


if __name__ == "__main__":
    main()
