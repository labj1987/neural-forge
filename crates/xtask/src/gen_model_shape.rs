//! Writes crates/supervisor/src/model_shape.rs: the tensor names and byte lengths the graph implements.
//!
//! Usage: cargo xtask gen-model-shape FULL_MANIFEST SMALL_MANIFEST BUILD
//!
//! FULL_MANIFEST and SMALL_MANIFEST are the `manifest.json` files that `neural-forge-cli extract-model`
//! wrote with `--network full` and `--network small` from one DLL whose networks the graph
//! (`nr::Topology` in third_party/opendlss-nr/src/nr_graph.*) implements; BUILD is that DLL's build, for the file
//! comment. Only each tensor's `name` and `byteLength` are read: no tensor bytes, no hashes.

use std::process::ExitCode;

use serde_json::Value;

const USAGE: &str = "Usage: cargo xtask gen-model-shape FULL_MANIFEST SMALL_MANIFEST BUILD";

fn rows(path: &str) -> Result<Vec<(String, u64)>, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))?;
    let manifest: Value = serde_json::from_str(&text).map_err(|e| format!("{path}: {e}"))?;
    let tensors = manifest["tensors"].as_array().ok_or_else(|| format!("{path}: no tensors"))?;
    tensors
        .iter()
        .map(|t| {
            let name = t["name"].as_str().ok_or_else(|| format!("{path}: a tensor without a name"))?;
            // `int()` takes the length as a number or as text.
            let length = match &t["byteLength"] {
                Value::Number(n) => n.as_u64(),
                Value::String(s) => s.trim().parse().ok(),
                _ => None,
            };
            let length = length.ok_or_else(|| format!("{path}: {name}: no byteLength"))?;
            Ok((name.to_string(), length))
        })
        .collect()
}

fn table(name: &str, doc: &str, entries: &[(String, u64)]) -> Vec<String> {
    let mut lines = vec![format!("/// {doc}"), format!("pub const {name}: &[(&str, u64)] = &[")];
    lines.extend(entries.iter().map(|(n, length)| format!("    (\"{n}\", {length}),")));
    lines.push("];".into());
    lines
}

/// The file's text.
pub fn render(full: &[(String, u64)], small: &[(String, u64)], build: &str) -> String {
    let mut lines: Vec<String> = [
        "//! The tensors the graph implements: each name in the weights resource and its byte length, for",
        "//! the full network (`WEIGHTS_HT`) and the small one (`WEIGHTS_CC_SMALL_FP8`).",
        "//!",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect();
    lines.push(format!("//! Generated by `cargo xtask gen-model-shape` from the manifests `extract-model` wrote from build {build}."));
    lines.extend(
        [
            "//! The rows describe the networks the graph builds (`nr::Topology` in `third_party/opendlss-nr/src/nr_graph.*`).",
            "//! A new network changes these tables with it: extend the topology, then regenerate them from manifests",
            "//! of a DLL that carries the new network.",
            "//!",
            "//! Names and lengths only: no tensor bytes and no hashes of them.",
            "",
        ]
        .iter()
        .map(|s| s.to_string()),
    );
    lines.extend(table("EXPECTED", "The full network: `(name, byte length)`, in the manifest's order (stage, then block, layer and parameter).", full));
    lines.push(String::new());
    lines.extend(table("EXPECTED_SMALL", "The small network, in the same order.", small));
    lines.join("\n") + "\n"
}

pub fn main(args: &[String]) -> ExitCode {
    if args.len() != 3 {
        eprintln!("{USAGE}");
        return ExitCode::FAILURE;
    }
    let (full, small) = match (rows(&args[0]), rows(&args[1])) {
        (Ok(full), Ok(small)) => (full, small),
        (Err(e), _) | (_, Err(e)) => {
            eprintln!("{e}");
            return ExitCode::FAILURE;
        }
    };
    let out = crate::root().join("crates/supervisor/src/model_shape.rs");
    if let Err(e) = std::fs::write(&out, render(&full, &small, &args[2])) {
        eprintln!("{}: {e}", out.display());
        return ExitCode::FAILURE;
    }
    for (label, entries) in [("full", &full), ("small", &small)] {
        println!("{}: {label} {} tensors, {} bytes", out.display(), entries.len(), entries.iter().map(|(_, l)| l).sum::<u64>());
    }
    ExitCode::SUCCESS
}

#[cfg(test)]
mod tests {
    #[test]
    fn render_lists_both_networks() {
        let full = vec![("a.w".to_string(), 4), ("a.b".to_string(), 2)];
        let small = vec![("s.w".to_string(), 8)];
        let text = super::render(&full, &small, "310.9");
        assert!(text.contains("from build 310.9.\n"));
        assert!(text.contains("pub const EXPECTED: &[(&str, u64)] = &[\n    (\"a.w\", 4),\n    (\"a.b\", 2),\n];\n\n"));
        assert!(text.ends_with("pub const EXPECTED_SMALL: &[(&str, u64)] = &[\n    (\"s.w\", 8),\n];\n"));
    }
}
